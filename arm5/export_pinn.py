"""Export the 5-joint motion PINN as ../arm5-pinn-weights.js for arm5.html."""
import argparse
import base64
import json
from pathlib import Path

import numpy as np
import torch

from motion import T_MIN, T_REF

HERE = Path(__file__).parent
OUT = HERE.parent / "arm5-pinn-weights.js"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", default="arm5_pinn.pt")
    args = ap.parse_args()
    ck = torch.load(HERE / args.ckpt, map_location="cpu")
    tensors = {}
    for name, t in ck["state"].items():
        arr = np.ascontiguousarray(t.float().numpy().astype("<f4"))
        tensors[name] = {"shape": list(arr.shape), "b64": base64.b64encode(arr.tobytes()).decode()}
    payload = {"layers": 4, "tensors": tensors, "t_ref": T_REF, "t_min": T_MIN, "payload_scale": 12.0}
    evp = HERE / "pinn_eval.json"
    if evp.exists():
        payload["eval"] = json.loads(evp.read_text())["random_moves"]
    OUT.write_text("// 5-joint motion PINN (generated by arm5/export_pinn.py)\nwindow.ARM5_PINN = "
                   + json.dumps(payload, separators=(",", ":")) + ";\n")
    print(f"wrote {OUT} ({OUT.stat().st_size / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
