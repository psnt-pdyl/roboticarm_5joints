"""Export the 5-joint arm's GNN and its geometry and physics as ../arm5-weights.js for arm5.html.

Also the motion GNN: python export.py --ckpt arm5_mgnn.pt --out ../arm5-mgnn-weights.js --name ARM5_MGNN --eval mgnn_eval.json
"""
import base64
import json
from pathlib import Path

import numpy as np
import torch

import kin

HERE = Path(__file__).parent


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", default="arm5_gnn.pt")
    ap.add_argument("--eval", default="eval.json")
    ap.add_argument("--out", default="../arm5-weights.js")
    ap.add_argument("--name", default="ARM5", help="the window variable the page reads")
    args = ap.parse_args()
    ck = torch.load(HERE / args.ckpt, map_location="cpu")
    tensors = {}
    for name, t in ck["state"].items():
        arr = np.ascontiguousarray(t.float().numpy().astype("<f4"))
        tensors[name] = {"shape": list(arr.shape), "b64": base64.b64encode(arr.tobytes()).decode()}
    arm = {"n": kin.N, "len_mm": kin.LEN_MM.tolist(), "sh": list(kin.SH), "lim": kin.LIM.tolist(),
           "mass": kin.MASS.tolist(), "com_m": kin.LINK_COM.tolist(), "inertia": kin.LINK_I.tolist(),
           "tau_max": kin.TAU_MAX.tolist(), "payload_max": kin.PAYLOAD_MAX,
           "part_mass": kin.PART_MASS, "g": kin.G}
    payload = {"hidden": ck["hidden"], "steps": ck["steps"], "tensors": tensors, "arm": arm}
    if "time_all" in ck:
        payload["time_all"] = ck["time_all"]          # motion GNN: moment and duration on every node
    evp = HERE / args.eval
    if evp.exists():
        payload["eval"] = json.loads(evp.read_text())
    out = (HERE / args.out).resolve()
    out.write_text(f"// 5-joint arm {args.ckpt}, geometry and physics (generated by arm5/export.py)\nwindow.{args.name} = "
                   + json.dumps(payload, separators=(",", ":")) + ";\n")
    n = sum(int(np.prod(v["shape"])) for v in tensors.values())
    print(f"wrote {out} ({out.stat().st_size / 1e6:.2f} MB, {n:,} values)")


if __name__ == "__main__":
    main()
